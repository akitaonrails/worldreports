"""Australia's twelve page cards, computed from the committed CSVs.

Every figure and every sparkline is read out of `data/` at build time, so a
card cannot drift from its plate: they are two renderings of one file. The
headline strip leads with GDP, GDP per person and population, in that order,
the way every country's does, and then carries the four readings an
Australian page needs to be read at all.
"""
from __future__ import annotations

MONEY, WORLD, PEOPLE = "money", "world", "people"


def _mn(ctx, path, column):
    """One column in millions, the unit a population card is read in."""
    return [(y, v / 1e6) for y, v in ctx.col(path, column)]


def headline(ctx):
    T = ctx.text
    return [
        ctx.stat(T(en="GDP", pt="PIB"),
                 ctx.col("world/gdp_and_reserves.csv", "gdp_usd_bn"),
                 "usd_bn", kind="level"),
        ctx.stat(T(en="GDP per person, US$", pt="PIB por pessoa, US$"),
                 ctx.col("world/gdp_and_reserves.csv", "gdp_per_person_usd"),
                 "count", kind="level"),
        ctx.stat(T(en="Population", pt="População"),
                 _mn(ctx, "demography/population.csv", "population_jun30"),
                 "pop_mn", kind="level"),
        ctx.stat(T(en="Real GDP growth", pt="Crescimento real do PIB"),
                 ctx.col("macro/economy.csv", "real_growth_pct"), "pct_s"),
        ctx.stat(T(en="Inflation", pt="Inflação"),
                 ctx.col("macro/economy.csv", "cpi_inflation_pct"), "pct"),
        ctx.stat(T(en="Unemployment", pt="Desemprego"),
                 ctx.col("macro/economy.csv", "unemployment_pct"), "pct"),
        ctx.stat(T(en="Cash rate", pt="Taxa básica"),
                 ctx.col("markets/policy_rate.csv", "policy_rate_pct"),
                 "pct", kind="level"),
    ]


